#!/usr/bin/env python3
"""Generate a stress-test DXF (the "thunder drawing"): ~97k entities, 5 layers.

Output: thunder.dxf (R12-style, minimal sections) for the HoCAD emulator
benchmark. Not committed; regenerated by packaging/harmony/tools/gen-thunder-dxf.py.
"""
import math
import random

random.seed(2607)

W = []  # DXF text pieces
add = W.append

def line(layer, x1, y1, x2, y2):
    add(f"0\nLINE\n8\n{layer}\n10\n{x1:.3f}\n20\n{y1:.3f}\n11\n{x2:.3f}\n21\n{y2:.3f}\n")

def circle(layer, x, y, r):
    add(f"0\nCIRCLE\n8\n{layer}\n10\n{x:.3f}\n20\n{y:.3f}\n40\n{r:.3f}\n")

def arc(layer, x, y, r, a1, a2):
    add(f"0\nARC\n8\n{layer}\n10\n{x:.3f}\n20\n{y:.3f}\n40\n{r:.3f}\n50\n{a1:.1f}\n51\n{a2:.1f}\n")

def text(layer, x, y, h, s):
    add(f"0\nTEXT\n8\n{layer}\n10\n{x:.3f}\n20\n{y:.3f}\n40\n{h:.3f}\n1\n{s}\n")

def rect(layer, x, y, w, h):
    line(layer, x, y, x + w, y)
    line(layer, x + w, y, x + w, y + h)
    line(layer, x + w, y + h, x, y + h)
    line(layer, x, y + h, x, y)

ENT = 0
GRID = 160.0
CITY = 64  # 64x64 blocks
span = CITY * GRID

# Streets: every grid line drawn as one long pair per block boundary row/col
for i in range(CITY + 1):
    x = i * GRID
    add_line = (lambda a, b, c, d: line("STREETS", a, b, c, d))
    # one long street line per row/col (2 lines each)
    add_line(0, x, span, x)
    add_line(x, 0, x, span)
    ENT += 2

# Buildings: a rectangle (4 lines) per block, plus an interior detail grid (8 lines)
for bx in range(CITY):
    for by in range(CITY):
        x0, y0 = bx * GRID + 12, by * GRID + 12
        bw, bh = GRID - 24, GRID - 24
        rect("BUILDINGS", x0, y0, bw, bh)
        # interior rooms: 2 vertical + 2 horizontal partitions
        for k in (1, 2, 3):
            line("GRID", x0 + bw * k / 4, y0, x0 + bw * k / 4, y0 + bh)
            line("GRID", x0, y0 + bh * k / 4, x0 + bw, y0 + bh * k / 4)
        ENT += 12

# Water: circles + arcs sprinkled around
for _ in range(12000):
    x = random.uniform(0, span)
    y = random.uniform(0, span)
    r = random.uniform(2, 18)
    if random.random() < 0.5:
        circle("WATER", x, y, r)
        ENT += 1
    else:
        a1 = random.uniform(0, 180)
        arc("WATER", x, y, r, a1, a1 + random.uniform(60, 180))
        ENT += 1

# Labels: block names
for bx in range(0, CITY, 4):
    for by in range(0, CITY, 4):
        text("LABELS", bx * GRID + GRID / 2, by * GRID + GRID / 2, 6, f"B{bx}-{by}")
        ENT += 1

header = (
    "0\nSECTION\n2\nHEADER\n9\n$ACADVER\n1\nAC1009\n"
    "9\n$INSBASE\n10\n0.0\n20\n0.0\n30\n0.0\n0\nENDSEC\n"
)
layers = "".join(
    f"0\nLAYER\n2\n{name}\n70\n0\n62\n{color}\n6\nCONTINUOUS\n"
    for name, color in (("GRID", 8), ("STREETS", 2), ("BUILDINGS", 4), ("WATER", 5), ("LABELS", 3))
)
tables = (
    "0\nSECTION\n2\nTABLES\n0\nTABLE\n2\nLAYER\n70\n5\n"
    + layers
    + "0\nENDTAB\n0\nENDSEC\n"
)
entities = "0\nSECTION\n2\nENTITIES\n" + "".join(W) + "0\nENDSEC\n0\nEOF\n"

dxf = header + tables + entities
with open(r"C:\Users\jw\thunder.dxf", "w", newline="\n") as f:
    f.write(dxf)

print(f"entities ~= {ENT}, bytes = {len(dxf)}")
